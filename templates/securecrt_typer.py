# $interface = "1.0"

"""
Generated by cisco-ai-builder for __HOSTNAME__ (pod __POD__).

Types the config into the CURRENT SecureCRT tab one line at a time and waits for the
switch to answer before sending the next line (no lost lines on a 9600-baud console).

How to use it by hand:
  1. Connect to the device in SecureCRT (console cable / COM port, or telnet).
  2. Script > Run... > pick this file.
builder.py --securecrt does both steps for you.

(SecureCRT reads every '#' line at the very top as a '# $setting = value' header,
so only the two header lines above may start with '#'.)
"""

HOSTNAME = __HOSTNAME_REPR__
MGMT_IP = __MGMT_IP_REPR__
USERNAME = __USERNAME_REPR__
PASSWORDS = __PASSWORDS_REPR__
LINES = __LINES_REPR__

STEP_MS = 1500          # pause while walking through boot / login prompts
LINE_TIMEOUT = 20       # seconds to wait for the switch after each line
SLOW_TIMEOUT = 120      # crypto key generate / write memory take longer

# "% Generating 1024 bit RSA keys" is fine; these words mean IOS rejected the line.
BAD_WORDS = ("invalid", "incomplete", "ambiguous", "unknown", "error", "denied", "fail", "bad ", "not ")

BUTTON_YESNO = 4
IDYES = 6


def screen_line(scr):
    row = scr.CurrentRow
    return scr.Get(row, 1, row, scr.Columns).strip()


def reach_enable(scr):
    """Walk from whatever state the device is in (fresh boot, login, user mode,
    config mode) to the privileged EXEC '#' prompt."""
    pw_tries = 0
    scr.Send("\r")
    for _ in range(45):
        crt.Sleep(STEP_MS)
        line = screen_line(scr)
        low = line.lower()
        if "[yes/no]" in low:
            # Fresh switch: "Would you like to enter the initial configuration dialog?"
            scr.Send("no\r")
            crt.Sleep(3000)
        elif "[yes]" in low or "[confirm]" in low:
            # "Would you like to terminate autoinstall? [yes]:"
            scr.Send("\r")
        elif "return to get started" in low:
            scr.Send("\r")
        elif low.endswith("username:"):
            scr.Send(USERNAME + "\r")
        elif low.endswith("password:"):
            if pw_tries >= len(PASSWORDS) + 2:
                return "wrong password (tried: %s)" % ", ".join(PASSWORDS)
            scr.Send(PASSWORDS[pw_tries % len(PASSWORDS)] + "\r")
            pw_tries += 1
        elif "(config" in line and line.endswith("#"):
            scr.Send("end\r")
        elif line.endswith("#"):
            return None
        elif line.endswith(">"):
            scr.Send("enable\r")
        elif "--more--" in low:
            scr.Send(" ")
        elif line.startswith("switch:") or line.startswith("rommon"):
            return "the device is in ROMMON/boot loader (type 'boot' first)"
        else:
            scr.Send("\r")
    return "no '#' prompt after a minute"


def send_config(scr):
    """Send every line, wait for the prompt, collect anything IOS complains about."""
    problems = []
    scr.Synchronous = True
    for cmd in LINES:
        scr.Send(cmd + "\r")
        slow = cmd.startswith("crypto key") or cmd.startswith("write") or cmd.startswith("copy")
        out = ""
        while True:
            chunk = scr.ReadString(["#", "[yes/no]", "[confirm]", "]?"], SLOW_TIMEOUT if slow else LINE_TIMEOUT)
            out += chunk
            hit = scr.MatchIndex
            if hit == 0:
                problems.append(cmd + "   -> no reply (timed out)")
                break
            if hit == 2:        # "Do you really want to replace them? [yes/no]"
                scr.Send("yes\r")
                continue
            if hit in (3, 4):   # "[confirm]" / "Destination filename [startup-config]?"
                scr.Send("\r")
                continue
            break
        for text in out.splitlines():
            text = text.strip()
            if (text.startswith("% ") and "encapsulation" not in cmd
                    and any(w in text.lower() for w in BAD_WORDS)):
                problems.append(cmd + "   -> " + text)
                break
    scr.Synchronous = False
    return problems


def is_serial(tab):
    try:
        return tab.Session.Config.GetOption("Protocol Name").lower() == "serial"
    except Exception:
        return False


def main():
    tab = crt.GetScriptTab()
    scr = tab.Screen
    for _ in range(40):  # telnet may still be connecting when the script starts
        if tab.Session.Connected:
            break
        crt.Sleep(500)
    if not tab.Session.Connected:
        crt.Dialog.MessageBox("Not connected. Connect to %s first (console cable or telnet), then run this script again." % HOSTNAME)
        return

    scr.Synchronous = False
    scr.IgnoreEscape = True
    trouble = reach_enable(scr)
    if trouble:
        crt.Dialog.MessageBox("%s: couldn't get to the '#' prompt: %s.\n\nFix it in the window, then run the script again." % (HOSTNAME, trouble))
        return

    problems = send_config(scr)
    msg = "%s: typed %d lines.\n" % (HOSTNAME, len(LINES))
    if problems:
        msg += "\nIOS complained about %d line(s):\n  %s\n" % (len(problems), "\n  ".join(problems[:12]))
    else:
        msg += "No errors.\n"
    if MGMT_IP:
        msg += "\nCheck it: from a PC in VLAN 1 run  telnet %s  (password: %s)" % (MGMT_IP, PASSWORDS[0])

    if is_serial(tab):
        msg += "\n\nDisconnect the console now so you can move the cable to the next device?"
        if crt.Dialog.MessageBox(msg, HOSTNAME, BUTTON_YESNO) == IDYES:
            tab.Session.Disconnect()
    else:
        crt.Dialog.MessageBox(msg, HOSTNAME)


main()
