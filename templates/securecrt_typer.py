# $interface = "1.0"

"""
Generated by cisco-ai-builder for pod __POD__: __TITLE__.

Types each device's config into the CURRENT SecureCRT tab, one line at a time, waiting
for the device to answer before the next line (no lost lines on a 9600-baud console).

With more than one device it stays in the same tab (e.g. Serial-COM3) and asks you to
move the console cable to the next device before typing its config.

How to use it by hand:
  1. Connect in SecureCRT (console cable / COM port, or telnet).
  2. Script > Run... > pick this file.
builder.py --securecrt does both steps for you.

(SecureCRT reads every '#' line at the very top as a '# $setting = value' header,
so only the two header lines above may start with '#'.)
"""

DEVICES = __DEVICES_REPR__
USERNAME = __USERNAME_REPR__
PASSWORDS = __PASSWORDS_REPR__

STEP_MS = 1500          # pause while walking through boot / login prompts
LINE_TIMEOUT = 20       # seconds to wait for the device after each line
SLOW_TIMEOUT = 120      # crypto key generate / write memory take longer
CTRL_C = chr(3)

# "% Generating 1024 bit RSA keys" is fine; these words mean IOS rejected the line.
BAD_WORDS = ("invalid", "incomplete", "ambiguous", "unknown", "error", "denied", "fail", "bad ", "not ")

BUTTON_YESNOCANCEL = 3
IDYES, IDNO, IDCANCEL = 6, 7, 2


def screen_line(scr):
    row = scr.CurrentRow
    return scr.Get(row, 1, row, scr.Columns).strip()


def reach_enable(scr):
    """Walk from whatever state the device is in (fresh boot, login, user mode,
    config mode) to the privileged EXEC '#' prompt."""
    pw_tries = 0
    scr.Send("\r")
    for _ in range(45):
        crt.Sleep(STEP_MS)
        line = screen_line(scr)
        low = line.lower()
        if "[yes/no]" in low or "initial configuration dialog" in low:
            # Fresh switch: don't answer the setup dialog, abort it with Ctrl+C.
            scr.Send(CTRL_C)
            crt.Sleep(3000)
        elif "[yes]" in low or "[confirm]" in low:
            # "Would you like to terminate autoinstall? [yes]:"
            scr.Send("\r")
        elif "return to get started" in low:
            scr.Send("\r")
        elif low.endswith("username:"):
            scr.Send(USERNAME + "\r")
        elif low.endswith("password:"):
            if pw_tries >= len(PASSWORDS) + 2:
                return "wrong password (tried: %s)" % ", ".join(PASSWORDS)
            scr.Send(PASSWORDS[pw_tries % len(PASSWORDS)] + "\r")
            pw_tries += 1
        elif "(config" in line and line.endswith("#"):
            scr.Send("end\r")
        elif line.endswith("#"):
            return None
        elif line.endswith(">"):
            scr.Send("enable\r")
        elif "--more--" in low:
            scr.Send(" ")
        elif line.startswith("switch:") or line.startswith("rommon"):
            return "the device is in ROMMON/boot loader (type 'boot' first)"
        else:
            scr.Send("\r")
    return "no '#' prompt after a minute"


def send_config(scr, lines):
    """Send every line, wait for the prompt, collect anything IOS complains about."""
    problems = []
    scr.Synchronous = True
    for cmd in lines:
        scr.Send(cmd + "\r")
        slow = cmd.startswith("crypto key") or cmd.startswith("write") or cmd.startswith("copy")
        out = ""
        while True:
            chunk = scr.ReadString(["#", "[yes/no]", "[confirm]", "]?"], SLOW_TIMEOUT if slow else LINE_TIMEOUT)
            out += chunk
            hit = scr.MatchIndex
            if hit == 0:
                problems.append(cmd + "   -> no reply (timed out)")
                break
            if hit == 2:        # "Do you really want to replace them? [yes/no]" (RSA keys)
                scr.Send("yes\r")
                continue
            if hit in (3, 4):   # "[confirm]" / "Destination filename [startup-config]?"
                scr.Send("\r")
                continue
            break
        for text in out.splitlines():
            text = text.strip()
            if (text.startswith("% ") and "encapsulation" not in cmd
                    and any(w in text.lower() for w in BAD_WORDS)):
                problems.append(cmd + "   -> " + text)
                break
    scr.Synchronous = False
    return problems


def configure(scr, dev):
    """Returns a one-paragraph result for the summary."""
    trouble = reach_enable(scr)
    if trouble:
        return "%s: NOT configured - couldn't get to the '#' prompt: %s." % (dev["name"], trouble)
    problems = send_config(scr, dev["lines"])
    msg = "%s: typed %d lines, " % (dev["name"], len(dev["lines"]))
    if problems:
        msg += "IOS complained about %d:\n    %s" % (len(problems), "\n    ".join(problems[:8]))
    else:
        msg += "no errors."
    if dev["ip"]:
        msg += "\n    Check: telnet %s  (password: %s)" % (dev["ip"], PASSWORDS[0])
    return msg


def main():
    tab = crt.GetScriptTab()
    scr = tab.Screen
    for _ in range(40):  # telnet may still be connecting when the script starts
        if tab.Session.Connected:
            break
        crt.Sleep(500)
    if not tab.Session.Connected:
        crt.Dialog.MessageBox("Not connected. Connect to the device first (console cable or telnet), "
                              "then run this script again.")
        return

    scr.Synchronous = False
    scr.IgnoreEscape = True
    results = []
    for i, dev in enumerate(DEVICES):
        if len(DEVICES) > 1:
            where = "" if i == 0 else "Move the console cable to %s.\n\n" % dev["name"]
            ans = crt.Dialog.MessageBox(
                "%sIs the console cable plugged into %s?\n\n"
                "Yes = type its config    No = skip it    Cancel = stop" % (where, dev["name"]),
                "cisco-ai-builder (%d of %d)" % (i + 1, len(DEVICES)), BUTTON_YESNOCANCEL)
            if ans == IDCANCEL:
                results.append("Stopped before %s." % dev["name"])
                break
            if ans == IDNO:
                results.append("%s: skipped." % dev["name"])
                continue
        results.append(configure(scr, dev))

    crt.Dialog.MessageBox("\n\n".join(results), "cisco-ai-builder: done")


main()
